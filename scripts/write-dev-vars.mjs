// Regenerate apps/edge/.dev.vars from the decrypted apps/edge/.env.
//
// Wrangler builds the local dev and test Worker `env` by reading files off disk, so it
// never sees what dotenvx decrypted into process.env. Left alone it reads the encrypted
// .env and hands the Worker the literal "encrypted:..." string: a non-empty value that
// passes every truthiness check and only fails later, upstream. .dev.vars takes
// precedence over .env in wrangler's lookup, so writing the real values here is what
// makes env.<KEY> mean the same thing locally as it does in production.
//
// Deliberately runs without --strict: a contributor without a private key still gets a
// working `pnpm dev`, minus the values they cannot decrypt.

import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { runtimeKeys } from "./env-file.mjs";

const ENV_FILE = "apps/edge/.env";
const DEV_VARS_FILE = "apps/edge/.dev.vars";
const CIPHERTEXT_PREFIX = "encrypted:";

const lines = [];
const undecrypted = [];
const unrepresentable = [];

for (const key of runtimeKeys(ENV_FILE)) {
  const value = process.env[key];
  if (value === undefined || value === "") {
    continue;
  }
  if (value.startsWith(CIPHERTEXT_PREFIX)) {
    undecrypted.push(key);
    continue;
  }
  if (value.includes("\\")) {
    // A backslash cannot survive the round trip: the parser expands \n and \r but
    // leaves every other backslash literal, so there is no way to write one back
    // faithfully. Skip it rather than hand the Worker a corrupted secret.
    unrepresentable.push(key);
    continue;
  }
  // .dev.vars is dotenv syntax: the parser strips one leading and one trailing double
  // quote and expands \n and \r inside them. It does not process \" or \\, so inner
  // quotes are written bare and only real line breaks are escaped.
  lines.push(`${key}="${value.replace(/\r/g, "\\r").replace(/\n/g, "\\n")}"`);
}

if (unrepresentable.length > 0) {
  process.stderr.write(
    `Skipped ${unrepresentable.join(", ")}: a backslash in the value cannot be written to ${DEV_VARS_FILE} without corrupting it.\n`
  );
}

if (undecrypted.length > 0) {
  process.stderr.write(
    `Could not decrypt ${undecrypted.join(", ")} from ${ENV_FILE}. The local Worker will start without them.\n`
  );
}

const HEADER = `# Generated from ${ENV_FILE} by scripts/write-dev-vars.mjs. Do not edit or commit.`;

function wasGeneratedByUs() {
  try {
    return readFileSync(DEV_VARS_FILE, "utf8").startsWith(HEADER);
  } catch {
    return false;
  }
}

if (lines.length === 0) {
  // Clear a stale file we wrote, so an absent binding fails loudly at the use site
  // rather than silently using yesterday's value. Never touch a .dev.vars somebody
  // maintains by hand: it predates this script and is the only copy of what it holds.
  if (wasGeneratedByUs()) {
    rmSync(DEV_VARS_FILE, { force: true });
    process.stdout.write(
      `Removed the generated ${DEV_VARS_FILE}: nothing to write.\n`
    );
  } else {
    process.stdout.write(
      `No decrypted values to write, and ${DEV_VARS_FILE} was not generated by this script. Leaving it alone.\n`
    );
  }
} else {
  if (!wasGeneratedByUs()) {
    process.stderr.write(
      `Overwriting a hand-maintained ${DEV_VARS_FILE}. Its previous contents are not recoverable from ${ENV_FILE}.\n`
    );
  }
  writeFileSync(DEV_VARS_FILE, `${HEADER}\n${lines.join("\n")}\n`);
  process.stdout.write(
    `Wrote ${lines.length} value(s) to ${DEV_VARS_FILE}: ${lines.map((l) => l.split("=")[0]).join(", ")}.\n`
  );
}
